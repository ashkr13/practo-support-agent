"""Task 7: run the 3-agent CrewAI crew via .kickoff() under MOCK_LLM, showing which tools ran."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.crew import run_crew  # noqa: E402
from app.mock_llm import MockCrewLLM  # noqa: E402

QUERIES = [
    "How many hours before my appointment can I cancel without paying anything?",  # RAG tool
    "What is the status of APT-1027?",                                              # lookup tool
    "Can I reschedule APT-1003, and what is the cancellation window?",              # both tools
    "What is the capital of France?",                                               # RAG -> fallback
]

if __name__ == "__main__":
    print("MOCK_LLM=true  CREWAI_DISABLE_TELEMETRY=true  process=sequential  agents=3")
    for i, q in enumerate(QUERIES, 1):
        llm = MockCrewLLM(model="mock-react-llm")
        run = run_crew(q, llm)
        print(f"\n{'=' * 90}\nQ{i}: {q}")
        print("--- ReAct trace (text generated by the mock LLM, per agent):")
        for role, text in llm.trace:
            shown = text if len(text) < 260 else text[:260] + " ...[truncated]"
            print(f"  [{role}]\n    " + shown.replace("\n", "\n    "))
        print(f"--- tools actually executed by CrewAI: {[{'tool': c['tool'], 'args': c['args']} for c in run.tool_calls]}")
        print(f"--- LLM calls: {run.llm_calls}")
        print(f"--- validated CrewResponse:\n    {run.response.model_dump_json(indent=None)}")
